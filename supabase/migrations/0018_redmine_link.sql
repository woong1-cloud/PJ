-- 0018: 레드마인 이슈 연결
--
-- MOA 와 레드마인의 층을 나누기로 하면서(브랜드 접수·합의는 MOA, 기획·개발
-- 실행은 레드마인) 새로운 실패 지점이 하나 생겼다 — 인계 누락이다.
--
-- MOA 에는 '개발중'으로 남아 있는데 레드마인에 티켓이 없으면, 브랜드는
-- 진행되는 줄 알고 기다리고 실제로는 아무 일도 일어나지 않는다. 그 사실을
-- 알아챌 방법이 지금은 없다.
--
-- requirement_links(0009)에 넣지 않고 컬럼을 따로 둔다. 그쪽은 자유 링크라
-- 피그마든 노션이든 들어올 수 있고, 그러면 "레드마인에 안 넘어간 건이 몇 건"
-- 을 셀 수가 없다 — 주소 문자열로 추측해야 하는데 주소 체계가 바뀌면 조용히
-- 틀린다. 칸을 따로 두면 있거나 없거나 둘 중 하나다.
--
-- 번호가 아니라 주소 전체를 담는다. 사내 레드마인 호스트를 아직 모르고,
-- 호스트를 환경변수로 고정하면 나중에 주소가 바뀔 때 배포를 다시 해야 한다.
alter table requirements add column if not exists redmine_url text;

comment on column requirements.redmine_url is
  '레드마인 이슈 주소 전체. 비어 있으면 아직 실행 단계로 인계되지 않았다는 뜻.';
