-- trigramSimilarity 로 대조한 결과다.
--   EIMS 적립 소멸 기한 추가   100% (제목 동일)
--   브레이즈 고도화            100% (제목 동일)
--   클라리티 sdk 설치           50% (기존 '클라리티 sdk 삽입 요청')
-- 세 건 모두 기존 쪽 본문이 시트보다 자세해서 덮어쓰지 않는다.
--
-- 변환 규칙
--   상태     요청·검토·정책정의 → 전부 '검토대기'
--            MOA 의 '검토중' 은 담당자·예상일이 붙는 상태인데 시트에는 둘 다
--            없다. 없는 진행을 만들지 않는다. 원래 상태는 비고에 남긴다.
--   채널     시트에 없음 → 전부 '자사몰' (필수값이다)
--   담당자   시트의 하새란·윤다혜·안수아·장재혁은 MOA 팀원이 아니다 → 비움
--   우선순위 1→상, 2·3→중, 4→하, 빈칸→비움
--   유형     운영개선·긴급개선→개선, 프로젝트→신규
--            레퍼럴 이벤트만 예외로 '신규' 다 — 시트 구분은 운영개선이지만
--            TO-BE 가 "신규 이벤트 기능 개발 요청 건" 이라고 못박고 있다.
--   비고     시트의 비고 열만 옮긴다. 그 오른쪽 열들은 행과 맞지 않는 별도
--            메모(와탭 계약, 재무 계약, 크리마 관리 …)라 옮기면 틀린 정보가
--            섞인다.
--
-- 두 번 실행해도 안전하다. 같은 브랜드에 같은 제목이 있으면 건너뛴다.
-- 되돌리기는 파일 맨 아래 주석 참조.

