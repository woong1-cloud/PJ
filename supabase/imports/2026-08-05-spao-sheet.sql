  b.id,
  s.title,
  s.as_is,
  s.to_be,
  s.note,
  s.request_date::date,
  m.id,
  '검토대기',
  c.id,
  s.priority,
  '자사몰',
  s.req_type
from src s
cross join (select id from brands where name = '스파오') b
-- 요청자를 못 찾으면 비운다. 이름이 바뀌었다고 이관 전체가 멈추면 안 된다.
left join team_members m on m.name = s.requester_name
left join brand_categories c
  on c.brand_id = b.id and c.category_name = s.category_name
where not exists (
  select 1 from requirements r
  where r.brand_id = b.id and r.title = s.title
);

-- 브레이즈 고도화(기존 건)에 시트에만 있던 메모 한 줄을 덧붙인다.
-- 본문은 건드리지 않는다 — 기존 쪽이 더 정리되어 있다.
update requirements
set note = case
    when coalesce(note, '') = '' then '07/28 - 프로퍼티 정의필요'
    else note || E'\n07/28 - 프로퍼티 정의필요'
  end
where brand_id = (select id from brands where name = '스파오')
  and title = '브레이즈 고도화'
  and coalesce(note, '') not like '%프로퍼티 정의필요%';

commit;

