// 아직 안 본 소식.
//
// 날짜만 견준다. seenAt 은 시각까지 담기지만(onboarded_at 과 같은 timestamptz)
// 앞 열 글자만 잘라 본다 — 시각까지 견주면 소식을 본 그날 내내 창이 다시 뜬다.
//
// 읽을 수 없는 seenAt 은 한 번도 안 본 것으로 친다. 못 읽었다고 소식을 감추면
// 영영 못 보는데, 한 번 더 보는 쪽이 훨씬 가볍다.
//
// news 에 기본값을 두지 않는다. 부르는 쪽이 NEWS 를 넘긴다 — 기본값이 있으면
// undefined 를 넘겼을 때 조용히 전체 목록이 나와서, 빈 목록을 기대한 자리가
// 소식으로 가득 찬다.
export function unseenNews(news, seenAt = null) {
  const items = Array.isArray(news) ? news : [];
  const seenDate =
    typeof seenAt === 'string' && Number.isFinite(Date.parse(seenAt)) ? seenAt.slice(0, 10) : null;
  return items
    .filter((item) => item?.date && (!seenDate || item.date > seenDate))
    .sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : 0));
}
